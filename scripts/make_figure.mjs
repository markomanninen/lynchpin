// Writes the two generated TikZ drawings that the paper includes.
//   lynchpin-figure.tex   the Lynchpin in three dimensions, with its gaps
//   cell120-figure.tex    the 120-cell with the closed Lynchpin at one vertex
// Run with   node scripts/make_figure.mjs
import { writeFileSync } from "node:fs";
import * as L from "../lynchpin4d.js";

// Orthogonal projection to 3D, then a fixed view turned about the y and x
// axes, then the depth is dropped.
const ay = 0.55;
const ax = 0.32;
const flat = (p4, scale) => {
  const [x, y, z] = L.project(p4);
  const x1 = Math.cos(ay) * x + Math.sin(ay) * z;
  const z1 = -Math.sin(ay) * x + Math.cos(ay) * z;
  const y1 = Math.cos(ax) * y - Math.sin(ax) * z1;
  return `(${(x1 * scale).toFixed(3)},${(y1 * scale).toFixed(3)})`;
};
const colors = ["red", "green!70!black", "blue", "orange", "violet", "cyan!70!black"];
const origin = [0, 0, 0, 0];
const save = (name, lines) =>
  writeFileSync(
    new URL(`../${name}`, import.meta.url),
    ["% Generated by scripts/make_figure.mjs", "\\begin{tikzpicture}", ...lines, "\\end{tikzpicture}", ""].join("\n")
  );
const figure = (fig, scale) => [
  ...fig.pentagons.map(
    (p, k) =>
      `\\filldraw[${colors[k]}, fill opacity=0.3, line width=0.6pt] ${p.map((q) => flat(q, scale)).join(" -- ")} -- cycle;`
  ),
  ...fig.rays.map((r) => `\\draw[black, line width=1pt] ${flat(origin, scale)} -- ${flat(r, scale)};`),
];

// The Lynchpin in three dimensions with the tetrahedron and vertex labels.
{
  const scale = 3.2;
  const fig = L.lynchpin(0);
  const lines = L.PAIRS.map(
    ([i, j]) => `\\draw[black!50, dashed, line width=0.4pt] ${flat(fig.rays[i], scale)} -- ${flat(fig.rays[j], scale)};`
  );
  lines.push(...figure(fig, scale));
  ["A", "B", "C", "D"].forEach((name, i) => {
    lines.push(`\\fill ${flat(fig.rays[i], scale)} circle (1.2pt);`);
    lines.push(`\\node at ${flat(L.scale(fig.rays[i], 1.13), scale)} {\\( ${name} \\)};`);
  });
  lines.push(`\\fill ${flat(origin, scale)} circle (1.5pt);`);
  save("lynchpin-figure.tex", lines);
}

// The 120-cell around the closed Lynchpin.
{
  const scale = 1.55;
  const cell = L.cell120AtVertex();
  const lines = cell.edges.map(
    ([i, j]) =>
      `\\draw[black!45, line width=0.15pt] ${flat(cell.points[i], scale)} -- ${flat(cell.points[j], scale)};`
  );
  lines.push(...figure(L.lynchpin(L.TILT_MAX), scale));
  save("cell120-figure.tex", lines);
}
console.log("wrote lynchpin-figure.tex and cell120-figure.tex");
